export function buildDefaultVariantsForProduct(product: Product): ProductVariant[] {
  if (product.variants && product.variants.length > 0) {
    return product.variants;
  }
  const primaryColor = product.colors[0] || { name: 'Azul Pastel', hex: '#A9D6F5' };
  const baseSku = (product.sku || product.id).toUpperCase();
  const perVariantStock = Math.max(2, Math.floor(product.stock / Math.max(1, product.sizes.length)));

  return product.sizes.map((size, idx) => ({
    id: `${product.id}-var-${idx + 1}`,
    size,
    colorName: primaryColor.name,
    colorHex: primaryColor.hex,
    stock: idx === 0 ? product.stock - perVariantStock * (product.sizes.length - 1) : perVariantStock,
    sku: `${baseSku}-${size.replace(/[^A-Z0-9]/gi, '')}`,
    price: product.price,
  }));
}

